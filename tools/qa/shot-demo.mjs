import path from "node:path";
import { fileURLToPath } from "node:url";
import { chromium } from "playwright";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 860 } });
page.on("pageerror", (e) => console.log("pageerror:", e.message));
await page.goto("file://" + path.join(root, "docs/book-mock.html"));
await page.waitForSelector(".rb-root");
await page.click("#tb-theme");
await page.waitForTimeout(100);
const dark = await page.evaluate(() => document.querySelector(".wfrp-recipe-book").classList.contains("rb-theme-dark"));
console.log("theme toggles:", dark);
await page.click("#tb-theme");
await page.click("#tb-sheet");
await page.waitForTimeout(150);
const sheetOpen = await page.locator("#rb-sheet-demo").count();
console.log("gm sheet opens:", sheetOpen === 1);
await page.screenshot({ path: path.join(root, "docs", "demo-overview.png") });
await browser.close();
